/**
 * Яндекс.Метрика для SPA. Сам счётчик ставится сниппетом в client/index.html —
 * он присылает хит один раз, на загрузку документа. Дальше роутер меняет
 * страницы без перезагрузки, и переходы на /cv и /case/<slug> в статистику не
 * попадали вовсе: в отчётах был виден только адрес входа. Поэтому на каждую
 * смену маршрута шлём хит руками (см. MetrikaHits в App.tsx).
 */

export const METRIKA_ID = 111828641;

declare global {
  interface Window {
    /* очередь сниппета: до загрузки tag.js вызовы копятся в ym.a и
       проигрываются, когда тег доедет. поэтому звать ym можно сразу */
    ym?: (id: number, action: string, ...args: unknown[]) => void;
  }
}

/** Хит о просмотре страницы: адрес, referer (откуда пришли внутри сайта) и
    заголовок вкладки — иначе в отчётах все внутренние страницы слиплись бы
    под заголовком главной. */
export function sendHit(url: string, referer?: string) {
  window.ym?.(METRIKA_ID, "hit", url, {
    referer,
    title: document.title,
  });
}
