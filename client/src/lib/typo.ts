/**
 * Микротипографика: расстановка неразрывных пробелов в русском тексте.
 *
 * Правило применяется на рендере, а не хардкодом в строках контента — так
 * невидимые U+00A0 не расползаются по исходнику, а любой новый текст получает
 * типографику автоматически. Работает по токенам (слова между пробелами),
 * поэтому поведение предсказуемое и легко проверяется глазами.
 *
 * Что склеивается:
 *   1. короткое служебное слово + следующее слово — предлоги, союзы, частицы
 *      («в проде», «и собрала», «не ломает») не остаются висеть в конце строки;
 *   2. слово + частица — «бы», «же», «ли» не начинают строку.
 *
 * Намеренно НЕ склеиваем числа с единицами и слова с тире: такие пары
 * становились длинными неразрывными токенами и раньше укорачивали строки на
 * мобильном.
 */

const NBSP = "\u00A0";

// служебные слова, которые не должны висеть в конце строки. одно- и
// двухбуквенные ловятся правилом по длине (см. isShort), здесь — длинные
const SHORT_WORDS = new Set([
  "без", "для", "как", "над", "под", "при", "про", "что", "это", "или",
  "уже", "так", "там", "где", "чем", "тем", "его", "две", "три", "оба",
  "ещё", "еще", "они", "она", "оно", "вне", "изо", "обо", "ото", "все",
  "всё", "нет", "чуть", "лишь",
]);

// частицы: приклеиваются к слову СЛЕВА
const CLITICS = new Set(["бы", "б", "же", "ж", "ли", "ль"]);

// слово без обрамляющей пунктуации: «в» из «(в», «„в“» и т.п.
function core(token: string) {
  return token.replace(/^[«"„([]+/, "").replace(/[»"“)\]]+$/, "");
}

// служебное слово, которое не должно висеть в конце строки
function isShort(token: string) {
  const word = core(token);
  // слово с запятой или точкой на конце — это конец фразы, склейка не нужна
  if (!/^[а-яёa-z]+$/i.test(word)) return false;
  return word.length <= 2 || SHORT_WORDS.has(word.toLowerCase());
}

/** ставит неразрывные пробелы; переносы \n сохраняются как есть */
export function typo(text: string): string {
  return text
    .split("\n")
    .map((line) => {
      const tokens = line.split(" ");
      let out = tokens[0] ?? "";
      for (let i = 1; i < tokens.length; i++) {
        const prev = tokens[i - 1];
        const next = tokens[i];
        // пустой токен = двойной пробел в исходнике: ничего не склеиваем
        const glue =
          prev !== "" &&
          next !== "" &&
          (CLITICS.has(core(next).toLowerCase()) || isShort(prev));
        out += (glue ? NBSP : " ") + next;
      }
      return out;
    })
    .join("\n");
}
